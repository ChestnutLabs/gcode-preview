/*
 * Dialect fixture generator (DD-005 phase 3, issue #75): deterministic
 * Chestnut-constructed PrusaSlicer-style and Orca/Bambu-style G-code with
 * realistic marker/comment structure (no copied slicer output).
 *
 * Usage: node tools/fixtures/make-dialect-fixtures.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const outDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../test-data/fixtures/dialects');
fs.mkdirSync(outDir, { recursive: true });

function square(cx, cy, size, e0, f) {
  const h = size / 2;
  return [
    `G1 X${cx - h} Y${cy - h} E${e0} F${f}`,
    `G1 X${cx + h} Y${cy - h} E${e0 + 1}`,
    `G1 X${cx + h} Y${cy + h} E${e0 + 2}`,
    `G1 X${cx - h} Y${cy + h} E${e0 + 3}`,
    `G1 X${cx - h} Y${cy - h} E${e0 + 4}`
  ];
}

// Tiny 1-bit PNG-ish payload for the thumbnail comment (opaque bytes; adapters never decode images).
const thumbBytes = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 1, 2, 3, 4, 5, 6, 7, 8]);
const thumbB64 = thumbBytes.toString('base64');

const prusa = [
  '; generated by PrusaSlicer 2.7.4+win64 on 2026-07-23',
  ';',
  `; thumbnail begin 16x16 ${thumbB64.length}`,
  `; ${thumbB64}`,
  '; thumbnail end',
  'G21',
  'G0 X50 Y50 Z0.2',
  ';TYPE:Skirt',
  ...square(110, 110, 80, 1, 1200),
  ';TYPE:External perimeter',
  ...square(110, 110, 40, 10, 1500),
  ';TYPE:Perimeter',
  ...square(110, 110, 36, 20, 1500),
  ';TYPE:Internal infill',
  ...square(110, 110, 30, 30, 2400),
  'G0 X110 Y110 Z0.4',
  ';TYPE:Solid infill',
  ...square(110, 110, 30, 40, 2000),
  '; Filament-specific end gcode',
  '; prusaslicer_config = begin',
  '; bed_shape = 0x0,250x0,250x210,0x210',
  '; max_print_height = 220',
  '; printer_model = MK4',
  '; prusaslicer_config = end',
  ''
].join('\n');
fs.writeFileSync(path.join(outDir, 'prusa-style-sample.gcode'), prusa);

const orca = [
  '; BambuStudio 01.09.00.60',
  '; HEADER_BLOCK_START',
  '; printer_model: Bambu Lab A1 mini',
  '; HEADER_BLOCK_END',
  'G21',
  'G0 X40 Y40 Z0.2',
  '; start printing object, unique id: 0 name: cube_left',
  '; FEATURE: Outer wall',
  ...square(60, 90, 30, 1, 1500),
  '; FEATURE: Inner wall',
  ...square(60, 90, 26, 10, 1500),
  '; FEATURE: Sparse infill',
  ...square(60, 90, 20, 20, 2400),
  '; stop printing object',
  '; start printing object, unique id: 1 name: cube_right',
  '; FEATURE: Outer wall',
  ...square(120, 90, 30, 30, 1500),
  '; FEATURE: Top surface',
  ...square(120, 90, 24, 40, 1800),
  '; stop printing object',
  '; CONFIG_BLOCK_START',
  '; printable_area = 0x0,180x0,180x180,0x180',
  '; printable_height = 180',
  '; CONFIG_BLOCK_END',
  ''
].join('\n');
fs.writeFileSync(path.join(outDir, 'orca-bambu-style-sample.gcode'), orca);

console.log('prusa-style-sample.gcode:', prusa.length, 'B');
console.log('orca-bambu-style-sample.gcode:', orca.length, 'B');
