/*
 * Generate a small, fully synthetic, MIT-clean colored 3MF used only as
 * documentation-media input for the model-renderer harness page
 * (tools/demo/model.html) and the screenshot in the README.
 *
 * The model is a three-block "tower" carrying real `<basematerials>` colors
 * (red / amber / green) so the render exercises the capability-honest
 * `materials: 'known'` path — three objects, three declared colors, no
 * third-party geometry. Output is written as a base64 ES module so the demo
 * can embed it without shipping a binary fixture or a runtime ZIP builder.
 *
 * Usage:  node tools/fixtures/make-model-3mf.mjs
 * Verify: the model-renderer's own parse3mf resolves it to objectCount 3,
 *         materials 'known' (see packages/gcode-model-renderer tests for the
 *         parse contract this exercises).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.resolve(__dirname, '../demo/src/model-fixture.js');

// ---- minimal stored-only ZIP (OPC container) ----
const CRC = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();
const crc32 = (buf) => {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const u16 = (n) => Buffer.from([n & 0xff, (n >>> 8) & 0xff]);
const u32 = (n) => Buffer.from([n & 0xff, (n >>> 8) & 0xff, (n >>> 16) & 0xff, (n >>> 24) & 0xff]);
function makeZip(files) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  for (const f of files) {
    const name = Buffer.from(f.name, 'utf8');
    const data = Buffer.from(f.data);
    const crc = crc32(data);
    const local = Buffer.concat([
      u32(0x04034b50),
      u16(20),
      u16(0),
      u16(0),
      u16(0),
      u16(0),
      u32(crc),
      u32(data.length),
      u32(data.length),
      u16(name.length),
      u16(0),
      name,
      data
    ]);
    locals.push(local);
    centrals.push(
      Buffer.concat([
        u32(0x02014b50),
        u16(20),
        u16(20),
        u16(0),
        u16(0),
        u16(0),
        u16(0),
        u32(crc),
        u32(data.length),
        u32(data.length),
        u16(name.length),
        u16(0),
        u16(0),
        u16(0),
        u16(0),
        u32(0),
        u32(offset),
        name
      ])
    );
    offset += local.length;
  }
  const cd = Buffer.concat(centrals);
  const eocd = Buffer.concat([
    u32(0x06054b50),
    u16(0),
    u16(0),
    u16(files.length),
    u16(files.length),
    u32(cd.length),
    u32(offset),
    u16(0)
  ]);
  return Buffer.concat([...locals, cd, eocd]);
}

// ---- geometry: an axis-aligned box as 12 triangles (8 vertices) ----
function box(x0, y0, z0, x1, y1, z1) {
  const v = [
    [x0, y0, z0],
    [x1, y0, z0],
    [x1, y1, z0],
    [x0, y1, z0],
    [x0, y0, z1],
    [x1, y0, z1],
    [x1, y1, z1],
    [x0, y1, z1]
  ];
  const f = [
    [0, 2, 1],
    [0, 3, 2],
    [4, 5, 6],
    [4, 6, 7],
    [0, 1, 5],
    [0, 5, 4],
    [1, 2, 6],
    [1, 6, 5],
    [2, 3, 7],
    [2, 7, 6],
    [3, 0, 4],
    [3, 4, 7]
  ];
  const verts = v.map(([x, y, z]) => `<vertex x="${x}" y="${y}" z="${z}"/>`).join('');
  const tris = f.map(([a, b, c]) => `<triangle v1="${a}" v2="${b}" v3="${c}"/>`).join('');
  return `<mesh><vertices>${verts}</vertices><triangles>${tris}</triangles></mesh>`;
}

const model = `<?xml version="1.0" encoding="UTF-8"?>
<model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">
 <resources>
  <basematerials id="1">
   <base name="red" displaycolor="#D64545"/>
   <base name="amber" displaycolor="#E0A32E"/>
   <base name="green" displaycolor="#3F9E52"/>
  </basematerials>
  <object id="10" type="model" pid="1" pindex="0">${box(-15, -15, 0, 15, 15, 12)}</object>
  <object id="11" type="model" pid="1" pindex="1">${box(-11, -11, 12, 11, 11, 24)}</object>
  <object id="12" type="model" pid="1" pindex="2">${box(-7, -7, 24, 7, 7, 34)}</object>
 </resources>
 <build>
  <item objectid="10"/>
  <item objectid="11"/>
  <item objectid="12"/>
 </build>
</model>`;

const b64 = makeZip([{ name: '3D/3dmodel.model', data: model }]).toString('base64');

const moduleSource = `// GENERATED by tools/fixtures/make-model-3mf.mjs — do not edit by hand.
// A fully synthetic, MIT-clean colored 3MF (three blocks with real basematerials
// colors) used only as documentation-media input for the model-renderer harness.
// Regenerate with:  node tools/fixtures/make-model-3mf.mjs
export const TOWER_3MF_BASE64 =
  '${b64}';
`;

fs.writeFileSync(outFile, moduleSource);
console.log(`wrote ${path.relative(path.resolve(__dirname, '../..'), outFile)} (${b64.length} base64 chars)`);
