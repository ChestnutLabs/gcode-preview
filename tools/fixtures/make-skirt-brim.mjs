/**
 * Generate a small PrusaSlicer-style G-code fixture with a MODEL wrapped by SKIRT + BRIM
 * adhesion features, for documentation media:
 *   - object-aware framing (`frameContent` 'object' vs 'all' — the skirt sits well outside the model)
 *   - setFeatureRoleVisible (hide Skirt/Brim to declutter the part)
 *
 * PrusaSlicer header → dialect detected `known`; `;TYPE:` markers → FeatureRole classification.
 * MIT-clean, deterministic, hand-generated (Chestnut Labs). Regenerate:
 *   node tools/fixtures/make-skirt-brim.mjs
 */
/* eslint-env node */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const CX = 110,
  CY = 110;
const HALF = 12; // 24 mm square model
const LAYERS = 14;
const DZ = 0.2;
const EF = 0.045; // filament mm per mm of XY move (0.2 layer, 0.4 nozzle-ish)

const out = [];
const p = (s) => out.push(s);
const dist = (ax, ay, bx, by) => Math.hypot(bx - ax, by - ay);

let cx = 0,
  cy = 0;
function travel(x, y) {
  p(`G1 X${x.toFixed(3)} Y${y.toFixed(3)} F9000`);
  cx = x;
  cy = y;
}
function extrudeTo(x, y, f) {
  p(`G1 X${x.toFixed(3)} Y${y.toFixed(3)} E${(dist(cx, cy, x, y) * EF).toFixed(5)} F${f}`);
  cx = x;
  cy = y;
}
/** A closed rectangular loop (corners are half-width `h` around the center). */
function loop(h, f) {
  travel(CX - h, CY - h);
  extrudeTo(CX + h, CY - h, f);
  extrudeTo(CX + h, CY + h, f);
  extrudeTo(CX - h, CY + h, f);
  extrudeTo(CX - h, CY - h, f);
}

p('; generated by PrusaSlicer 2.7.0+win64');
p('; MIT-clean documentation fixture: model + skirt + brim (Chestnut Labs)');
p('; bed_shape = 0x0,250x0,250x250,0x250');
p('; nozzle_diameter = 0.4');
p('M83 ; relative extrusion');
p('G21');
p('G90');

for (let l = 0; l < LAYERS; l++) {
  const z = (l + 1) * DZ;
  p(`;LAYER_CHANGE`);
  p(`G1 Z${z.toFixed(3)} F1200`);

  if (l === 0) {
    // Skirt: one loop well OUTSIDE the model (so object-aware framing differs from whole-job).
    p(';TYPE:Skirt');
    loop(HALF + 12, 1200);
    // Brim: a few loops hugging the model base, just outside the object outline.
    p(';TYPE:Brim');
    for (let bh = HALF + 3; bh > HALF; bh -= 1) loop(bh, 1200);
  }

  // Model walls: external + one inner perimeter.
  p(';TYPE:External perimeter');
  loop(HALF, 1800);
  p(';TYPE:Perimeter');
  loop(HALF - 1.2, 1800);

  // Model infill: parallel diagonal-ish lines filling the interior (simple boustrophedon).
  p(';TYPE:Internal infill');
  const inner = HALF - 2.4;
  const step = 2.0;
  let dir = 1;
  for (let x = CX - inner; x <= CX + inner + 1e-6; x += step) {
    const y0 = dir > 0 ? CY - inner : CY + inner;
    const y1 = dir > 0 ? CY + inner : CY - inner;
    travel(x, y0);
    extrudeTo(x, y1, 2400);
    dir *= -1;
  }
}

p('M400');
p('; end');

const dir = dirname(fileURLToPath(import.meta.url));
const dest = resolve(dir, '../../test-data/fixtures/annotations/skirt-brim-model.gcode');
writeFileSync(dest, out.join('\n') + '\n');
console.log(`wrote ${dest} (${out.length} lines)`);
