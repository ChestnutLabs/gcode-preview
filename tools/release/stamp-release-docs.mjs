/*
 * Doc-freshness stamper — runs inside the root `version` script (after `changeset version`),
 * so its edits land in the SAME commit as the lockstep version bump on the generated
 * "Version Packages" PR. Result: the deterministic "vX.Y.Z is on npm" strings move exactly
 * when the versions do, and a human-reviewable narrative draft rides along in the PR.
 *
 * It does two things:
 *   1) Stamps the DETERMINISTIC surfaces (SURFACES) to the new lockstep version.
 *   2) Writes RELEASE_NOTES_DRAFT.md — a proposed "Current state" lead + release-history line
 *      + the deduped changelog bullets — for the release author to fold into docs/README's
 *      curated narrative. The gate (check-release-docs.mjs) then requires that draft be
 *      removed and the narrative to name the new version, so the story lands WITH the release.
 *
 * Narrative prose is never auto-written into the docs — only proposed. Usage:
 *   node tools/release/stamp-release-docs.mjs            stamp + write draft
 *   node tools/release/stamp-release-docs.mjs --dry-run  report only, write nothing
 */
import fs from 'node:fs';
import path from 'node:path';
import {
  repoRoot,
  readVersion,
  SURFACES,
  DRAFT_FILE,
  currentVersionOf,
  applySurface,
  narrativeChecks,
  aggregateChangelog
} from './doc-surfaces.mjs';

const DRY = process.argv.includes('--dry-run');
const version = readVersion();

let stamped = 0;
let missing = 0;
for (const surface of SURFACES) {
  const file = path.join(repoRoot, surface.file);
  const before = fs.readFileSync(file, 'utf8');
  const current = currentVersionOf(surface, before);
  if (current === null) {
    process.stderr.write(`stamp-release-docs: ANCHOR MISSING in ${surface.file} (${surface.label})\n`);
    missing++;
    continue;
  }
  const after = applySurface(surface, before, version);
  if (after !== before) {
    stamped++;
    process.stderr.write(`stamp-release-docs: ${surface.file} ${surface.label} v${current} -> v${version}\n`);
    if (!DRY) fs.writeFileSync(file, after);
  }
}

if (missing > 0) {
  process.stderr.write(
    `stamp-release-docs: ${missing} anchor(s) missing — doc structure drifted; update tools/release/doc-surfaces.mjs\n`
  );
  process.exit(1);
}

// ---- Narrative draft (proposal only; never written into the docs themselves) ----
const { bullets, changedPackages } = aggregateChangelog(version);
const readmeDocs = fs.readFileSync(path.join(repoRoot, 'docs', 'README.md'), 'utf8');
const narrativeOk = narrativeChecks(readmeDocs, version).every((r) => r.ok);

const draft = `# Release notes draft — v${version}

> Auto-generated by \`tools/release/stamp-release-docs.mjs\` from this release's package
> CHANGELOGs. **Review and rewrite into prose**, fold it into the two curated surfaces in
> \`docs/README.md\`, then DELETE this file. The release gate (\`npm run docs:release-check\`)
> blocks promotion to \`main\` until this file is gone and those surfaces name v${version}.

## 1. Update the "Current state" block (docs/README.md)
Lead it with the new version, e.g.:

\`## Current state (updated <YYYY-MM-DD> — **v${version} shipped to npm** (14 lockstep pkgs): <one-to-three sentence story>. Prior: **v<previous>** …)\`

## 2. Add the release-history line (docs/README.md, the "publishing from tagged … Releases (…)" list)
Append: \`\` \`v${version}\` <short label> \`\`

## Proposed points (deduped from this release's changelogs)
${bullets.length ? bullets.map((b) => `- ${b}`).join('\n') : '- (no non-dependency changelog entries found — confirm this is intentional)'}

## Packages changed this release
${changedPackages.length ? changedPackages.map((p) => `- ${p}`).join('\n') : '- (none detected)'}

## Before you cut the tag — public-docs completion check (CLAUDE.md)
- [ ] Root README still accurate for any new user-visible capability?
- [ ] Package README / user guide updated where behavior changed?
- [ ] Any existing screenshot now misrepresents the software? (regenerate via tools/screenshots/)
- [ ] Quick-start / example code still shows the recommended API?
`;

const draftPath = path.join(repoRoot, DRAFT_FILE);
if (DRY) {
  process.stderr.write(
    `stamp-release-docs: [dry-run] would ${narrativeOk ? 'still write' : 'write'} ${DRAFT_FILE} (${bullets.length} points, ${changedPackages.length} pkgs)\n`
  );
} else {
  fs.writeFileSync(draftPath, draft);
  process.stderr.write(
    `stamp-release-docs: wrote ${DRAFT_FILE} (${bullets.length} points, ${changedPackages.length} pkgs) — fold into docs/README.md then delete it\n`
  );
}

process.stderr.write(`stamp-release-docs: stamped ${stamped} surface(s) to v${version}\n`);
