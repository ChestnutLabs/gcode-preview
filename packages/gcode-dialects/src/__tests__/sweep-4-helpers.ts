/** Parse + annotate exactly as the worker does. */
export function annotate(adapters: DialectAdapter[], lines: string[], selection: 'auto' | string[] = 'auto') {
  const text = lines.join('\n');
  const r = createDialectRunner(adapters).createRun({
    selection,
    headText: text.slice(0, 65536),
    tailText: text.slice(-16384)
  });
  if (r === null) return null;
  const { ir } = parseGcodeToIR(text, { onComment: r.onComment, onCommand: r.onCommand });
  const { metadata } = r.finalize(ir);
  const codes = ir.header.warnings.map((w) => w.code);
  const messages = (code: string) => ir.header.warnings.filter((w) => w.code === code).map((w) => w.message);
  return { ir, metadata, codes, messages };
}
export const must = (r: ReturnType<typeof annotate>) => {
  expect(r).not.toBeNull();
  return r!;
};

export type Seg = [number, number, number, number, number, number, number]; // x0 y0 z0 x1 y1 z1 kind
/** A finished IR from explicit segments; srcBytes 0, 10, 20, … */
export function irOf(segs: Seg[]): ToolpathIR {
  const b = new ToolpathIRBuilder({ parserVersion: 'test', units: 'mm', unitsSource: 'known' });
  segs.forEach(([x0, y0, z0, x1, y1, z1, kind], i) =>
    b.addSegment({ x0, y0, z0, x1, y1, z1, e: kind === MoveKind.Extrude ? 1 : 0, kind, layer: 0, srcByte: i * 10 })
  );
  return b.finalize();
}
export const E = MoveKind.Extrude;
export const T = MoveKind.Travel;
export const line = (n: number): Seg[] => Array.from({ length: n }, (_, i): Seg => [i, 0, 0.2, i + 1, 0, 0.2, E]);

export function applied(
  fill: (s: BufferedAnnotationSink) => void,
  ir: ToolpathIR = irOf(line(4)),
  md?: DialectMetadata
) {
  const sink = new BufferedAnnotationSink('t');
  fill(sink);
  const metadata: DialectMetadata = md ?? { dialects: [] };
  const conflicts: string[] = [];
  sink.apply(ir, metadata, (code) => conflicts.push(code));
  const warn = (code: string) => ir.header.warnings.filter((w) => w.code === code);
  return { ir, md: metadata, conflicts, warn };
}
