/**
 * CRLF end-to-end: the parser splits on `\n` only, so every comment reaches the adapters ending in
 * `\r`. Slicer settings (bed, height, printer, filament, print time) must survive that.
 */
import { describe, expect, it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseGcodeToIR } from '../../../gcode-parser/src/parse';
import { createDialectRunner } from '../registry';
import { prusaSlicer } from '../prusaslicer';
import { orcaBambu } from '../orca-bambu';
import { cura } from '../cura';
import { klipper, marlin, repRap } from '../firmware';

const fixtureDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../../../../test-data/fixtures/dialects'
);
const crlf = (text: string): string => text.replace(/\r?\n/g, '\r\n');
const loadCrlf = (name: string): string => crlf(fs.readFileSync(path.join(fixtureDir, name), 'utf8'));

function annotatedParse(text: string) {
  const run = createDialectRunner([prusaSlicer(), orcaBambu(), cura(), klipper(), marlin(), repRap()]).createRun({
    selection: 'auto',
    headText: text.slice(0, 64 * 1024),
    tailText: text.slice(-16 * 1024)
  });
  expect(run).not.toBeNull();
  const result = parseGcodeToIR(text, { onComment: run!.onComment, onCommand: run!.onCommand });
  return { ir: result.ir, metadata: run!.finalize(result.ir).metadata };
}

describe('CRLF files keep their slicer settings', () => {
  it('PrusaSlicer config block: bed, height, printer', () => {
    const text = loadCrlf('prusa-style-sample.gcode');
    expect(text).toContain('\r\n');
    const m = annotatedParse(text).metadata?.machine;
    expect(m?.bed).toEqual({ kind: 'rect', min: { x: 0, y: 0 }, max: { x: 250, y: 210 } });
    expect(m?.heightMm).toBe(220);
    expect(m?.printerName).toBe('MK4');
  });

  it('Orca/Bambu config block: printable area, height, printer', () => {
    const m = annotatedParse(loadCrlf('orca-bambu-style-sample.gcode')).metadata?.machine;
    expect(m?.bed).toEqual({ kind: 'rect', min: { x: 0, y: 0 }, max: { x: 180, y: 180 } });
    expect(m?.heightMm).toBe(180);
    expect(m?.printerName).toBe('Bambu Lab A1 mini');
  });

  it('multi-tool filament config: material per tool', () => {
    const { ir, metadata } = annotatedParse(loadCrlf('multitool-ams-sample.gcode'));
    expect(ir.tools.find((t) => t.id === 0)?.material).toBe('PLA');
    expect(ir.tools.find((t) => t.id === 1)?.material).toBe('PETG');
    expect(metadata?.filaments?.length).toBe(2);
  });

  it('PrusaSlicer filament totals + normal-mode print time', () => {
    const { metadata } = annotatedParse(
      crlf(
        [
          '; generated by PrusaSlicer 2.7.0 on 2024-01-01',
          'G1 X0 Y0 Z0.2 F1200',
          'G1 X10 Y0 E1',
          '; filament used [mm] = 2224.99',
          '; estimated printing time (normal mode) = 37m 15s',
          '; estimated printing time (silent mode) = 38m 0s',
          ''
        ].join('\n')
      )
    );
    expect(metadata?.filamentUsage).toMatchObject({ lengthMm: 2224.99 });
    expect(metadata?.printEstimate).toMatchObject({ seconds: 2235, mode: 'normal' });
  });

  it('Cura: print time, filament length', () => {
    const { metadata } = annotatedParse(
      crlf(
        [
          ';Generated with Cura_SteamEngine 5.6.0',
          'G1 X0 Y0 Z0.2 F1200',
          'G1 X10 Y0 E1',
          ';TIME:2235',
          ';Filament used: 2.22m',
          ''
        ].join('\n')
      )
    );
    expect(metadata?.printEstimate?.seconds).toBe(2235);
    expect(metadata?.filamentUsage?.lengthMm).toBeCloseTo(2220, 3);
  });

  it('Orca/Bambu: filament totals + colon-separated estimated time', () => {
    const { metadata } = annotatedParse(
      crlf(
        [
          '; generated by OrcaSlicer 2.0.0',
          'G1 X0 Y0 Z0.2 F1200',
          'G1 X10 Y0 E1',
          '; filament used [mm] = 1645.00',
          '; total estimated time: 27m 14s',
          ''
        ].join('\n')
      )
    );
    expect(metadata?.filamentUsage).toMatchObject({ lengthMm: 1645 });
    expect(metadata?.printEstimate?.seconds).toBe(1634);
  });

  it('Klipper EXCLUDE_OBJECT_* blocks still populate the object channel', () => {
    const { ir } = annotatedParse(loadCrlf('klipper-prusa-sample.gcode'));
    expect(ir.header.capabilities.objects).toBe('known');
    expect(ir.objects[0]).toEqual({ id: '1', name: 'cube' });
    expect(Array.from(ir.segments.object).filter((v) => v === 1).length).toBe(5);
  });

  it('Klipper-targeted PrusaSlicer file keeps bed + printer', () => {
    const m = annotatedParse(loadCrlf('klipper-prusa-sample.gcode')).metadata?.machine;
    expect(m?.bed).toEqual({ kind: 'rect', min: { x: 0, y: 0 }, max: { x: 300, y: 300 } });
    expect(m?.printerName).toBe('Voron24');
  });

  it('Marlin M486 object blocks', () => {
    const { ir } = annotatedParse(loadCrlf('marlin-m486-sample.gcode'));
    expect(ir.objects[0].name).toBe('object 0');
    expect(ir.objects[1].name).toBe('object 1');
  });
});
