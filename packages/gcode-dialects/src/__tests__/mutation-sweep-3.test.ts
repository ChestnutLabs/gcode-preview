/**
 * Mutation sweep 3 over EXISTING dialect code (G3 lane, 2026-11). Slicer comments are untrusted file
 * data: a numeric value that is NaN, Infinity, zero or negative where that is impossible is dropped
 * (the field is absent), with one deduped `dialect-metadata-invalid` warning — never passed on, and
 * never a failed parse. Expected values are literals, never the module's own constants.
 */
import { describe, expect, it } from 'vitest';
import {
  MoveKind,
  ToolpathIRBuilder,
  type DialectMetadata,
  type ThumbnailData,
  type ToolpathIR
} from '@chestnutlabs/toolpath-core';
import { parseGcodeToIR } from '../../../gcode-parser/src/parse';
import { createDialectRunner } from '../registry';
import { BufferedAnnotationSink } from '../sink';
import { grblLaser, grblMill } from '../cnc';
import { ThumbnailCollector, finiteNonNegative, finitePositive, parseAreaPoints } from '../annotate';
import { parseHmsToSeconds, prusaSlicer } from '../prusaslicer';
import { orcaBambu } from '../orca-bambu';
import { cura } from '../cura';
import type { AnnotationSink, DialectAdapter } from '../contracts';

/** 400 nines: parses to Infinity with Number()/parseFloat()/parseInt(). */
const HUGE = '9'.repeat(400);

function annotate(adapters: DialectAdapter[], lines: string[]) {
  const text = lines.join('\n');
  const r = createDialectRunner(adapters).createRun({
    selection: 'auto',
    headText: text.slice(0, 65536),
    tailText: text.slice(-16384)
  });
  expect(r).not.toBeNull();
  const { ir } = parseGcodeToIR(text, { onComment: r!.onComment, onCommand: r!.onCommand });
  const { metadata } = r!.finalize(ir);
  const invalid = ir.header.warnings.filter((w) => w.code === 'dialect-metadata-invalid');
  return { ir, metadata, invalid };
}

const PRUSA = '; generated by PrusaSlicer 2.8.1';
const ORCA = '; generated by OrcaSlicer 2.1.1';
const CURA = ';Generated with Cura_SteamEngine 5.6.0';

describe('finitePositive / finiteNonNegative', () => {
  it('keep only finite numbers in range', () => {
    expect(finitePositive(0.5)).toBe(0.5);
    expect(finitePositive(0)).toBeUndefined();
    expect(finitePositive(-1)).toBeUndefined();
    expect(finitePositive(Number.NaN)).toBeUndefined();
    expect(finitePositive(Infinity)).toBeUndefined();
    expect(finiteNonNegative(0)).toBe(0);
    expect(finiteNonNegative(2.5)).toBe(2.5);
    expect(finiteNonNegative(-0.1)).toBeUndefined();
    expect(finiteNonNegative(Number.NaN)).toBeUndefined();
    expect(finiteNonNegative(Infinity)).toBeUndefined();
  });
});

describe('print time that overflows to Infinity (defect: Infinity seconds)', () => {
  it('parseHmsToSeconds returns null and reports it; zero is null without a report', () => {
    let reports = 0;
    const onInvalid = () => reports++;
    expect(parseHmsToSeconds(`${HUGE}s`, onInvalid)).toBeNull();
    expect(parseHmsToSeconds(`${HUGE}d`, onInvalid)).toBeNull();
    expect(reports).toBe(2);
    expect(parseHmsToSeconds('0h 0m 0s', onInvalid)).toBeNull();
    expect(parseHmsToSeconds('garbage', onInvalid)).toBeNull();
    expect(reports).toBe(2);
    expect(parseHmsToSeconds('1s', onInvalid)).toBe(1);
    expect(parseHmsToSeconds(`${HUGE}s`)).toBeNull(); // the callback is optional
  });

  it('PrusaSlicer: no estimate, one warning', () => {
    const r = annotate([prusaSlicer()], [PRUSA, 'G1 X1 Y1', `; estimated printing time (normal mode) = ${HUGE}s`]);
    expect(r.metadata?.printEstimate).toBeUndefined();
    expect(r.invalid.map((w) => w.message)).toEqual(['estimated printing time out of range; dropped']);
  });

  it('Orca: an overflowing total falls back to the readable model time, with a warning', () => {
    const r = annotate(
      [orcaBambu()],
      ['; BambuStudio 01.09.00.70', `; model printing time: 5m; total estimated time: ${HUGE}s`, 'G1 X1']
    );
    expect(r.metadata?.printEstimate?.seconds).toBe(300);
    expect(r.invalid.map((w) => w.message)).toEqual(['print time out of range; dropped']);
  });

  it('Orca: an overflowing normal-mode time gives no estimate', () => {
    const r = annotate([orcaBambu()], [ORCA, 'G1 X1', `; estimated printing time (normal mode) = ${HUGE}m`]);
    expect(r.metadata?.printEstimate).toBeUndefined();
    expect(r.invalid.length).toBe(1);
  });
});

describe('Prusa-style filament totals (defect: NaN / Infinity)', () => {
  it('`.` and an overflowing value are dropped; a readable field on another line is kept', () => {
    const r = annotate(
      [prusaSlicer()],
      [
        PRUSA,
        'G1 X1 Y1',
        '; filament used [mm] = .',
        `; filament used [cm3] = ${HUGE}`,
        '; total filament used [g] = 1.2.3',
        '; filament used [mm] = 812.5'
      ]
    );
    expect(r.metadata?.filamentUsage?.lengthMm).toBe(812.5);
    expect(r.metadata?.filamentUsage?.volumeCm3).toBeUndefined();
    expect(r.metadata?.filamentUsage?.weightG).toBeUndefined();
    // deduped by code: one warning carrying the count, first message kept
    expect(r.invalid.length).toBe(1);
    expect(r.invalid[0].message).toBe("filament used [mm] value '.' unreadable; dropped");
    expect(r.invalid[0].count).toBe(3);
  });

  it('each field is dropped on its own (volume, weight), and 0 is a real amount', () => {
    const vol = annotate([prusaSlicer()], [PRUSA, 'G1 X1', `; filament used [cm3] = ${HUGE}`]);
    expect(vol.metadata?.filamentUsage).toBeUndefined();
    expect(vol.invalid[0].message).toBe(`filament used [cm3] value '${'9'.repeat(32)}' unreadable; dropped`);
    const g = annotate([prusaSlicer()], [PRUSA, 'G1 X1', '; total filament used [g] = .']);
    expect(g.metadata?.filamentUsage).toBeUndefined();
    expect(g.invalid[0].message).toBe("total filament used [g] value '.' unreadable; dropped");
    const zero = annotate([prusaSlicer()], [PRUSA, 'G1 X1', '; total filament used [g] = 0.00']);
    expect(zero.metadata?.filamentUsage?.weightG).toBe(0);
    expect(zero.invalid.length).toBe(0);
  });

  it('a dropped filament comment is still consumed (it is not re-read as key = value)', () => {
    const r = annotate([prusaSlicer()], [PRUSA, 'G1 X1', '; filament used [mm] = .', '; max_print_height = 210']);
    expect(r.metadata?.filamentUsage).toBeUndefined();
    expect(r.invalid.length).toBe(1);
  });

  it('Cura: a negative or unreadable `Filament used` is dropped with a warning', () => {
    const neg = annotate([cura()], [CURA, ';Filament used: -2.5m', 'G1 X1 Y1']);
    expect(neg.metadata?.filamentUsage).toBeUndefined();
    expect(neg.invalid.map((w) => w.message)).toEqual(['Filament used value unreadable; dropped']);
    const bad = annotate([cura()], [CURA, ';Filament used: m', 'G1 X1 Y1']);
    expect(bad.metadata?.filamentUsage).toBeUndefined();
    expect(bad.invalid.length).toBe(1);
    const zero = annotate([cura()], [CURA, ';Filament used: 0m', 'G1 X1 Y1']);
    expect(zero.metadata?.filamentUsage?.lengthMm).toBe(0);
    expect(zero.invalid.length).toBe(0);
  });
});

describe('bed points that overflow to Infinity (defect: infinite build volume)', () => {
  it('parseAreaPoints rejects a non-finite X or Y', () => {
    expect(parseAreaPoints(`0x0,${HUGE}x0,10x10`)).toBeNull();
    expect(parseAreaPoints(`0x0,10x${HUGE},10x10`)).toBeNull();
    expect(parseAreaPoints('0x0,10x0,10x10')).toEqual([
      { x: 0, y: 0 },
      { x: 10, y: 0 },
      { x: 10, y: 10 }
    ]);
  });

  it('PrusaSlicer / Orca: no machine, and the existing bed-unparsed warning', () => {
    const p = annotate([prusaSlicer()], [PRUSA, 'G1 X1', `; bed_shape = 0x0,${HUGE}x0,${HUGE}x210,0x210`]);
    expect(p.metadata?.machine).toBeUndefined();
    expect(p.ir.header.warnings.map((w) => w.code)).toContain('dialect-bed-unparsed');
    const o = annotate([orcaBambu()], [ORCA, 'G1 X1', `; printable_area = 0x0,250x0,250x${HUGE},0x${HUGE}`]);
    expect(o.metadata?.machine).toBeUndefined();
    expect(o.ir.header.warnings.map((w) => w.code)).toContain('dialect-bed-unparsed');
  });
});

describe('print height that is not a positive number (defect: negative build volume)', () => {
  const bed = '; bed_shape = 0x0,250x0,250x210,0x210';
  for (const [value, label] of [
    ['-5', 'negative'],
    ['0', 'zero'],
    [HUGE, 'overflowing'],
    ['abc', 'unreadable']
  ] as const) {
    it(`PrusaSlicer: a ${label} max_print_height leaves the bed with no height, with a warning`, () => {
      const r = annotate([prusaSlicer()], [PRUSA, 'G1 X1', bed, `; max_print_height = ${value}`]);
      expect(r.metadata?.machine?.bed).toEqual({ kind: 'rect', min: { x: 0, y: 0 }, max: { x: 250, y: 210 } });
      expect(r.metadata?.machine?.heightMm).toBeUndefined();
      expect(r.invalid.map((w) => w.message)).toEqual(['max_print_height is not a positive number; dropped']);
    });
  }

  it('PrusaSlicer: 0.5 is kept', () => {
    const r = annotate([prusaSlicer()], [PRUSA, 'G1 X1', bed, '; max_print_height = 0.5']);
    expect(r.metadata?.machine?.heightMm).toBe(0.5);
    expect(r.invalid.length).toBe(0);
  });

  it('Orca: a negative printable_height is dropped; 250 is kept', () => {
    const area = '; printable_area = 0x0,250x0,250x210,0x210';
    const bad = annotate([orcaBambu()], [ORCA, 'G1 X1', area, '; printable_height = -1']);
    expect(bad.metadata?.machine?.heightMm).toBeUndefined();
    expect(bad.invalid.map((w) => w.message)).toEqual(['printable_height is not a positive number; dropped']);
    const ok = annotate([orcaBambu()], [ORCA, 'G1 X1', area, '; printable_height = 250']);
    expect(ok.metadata?.machine?.heightMm).toBe(250);
    expect(ok.invalid.length).toBe(0);
  });
});

describe('thumbnail-comment dimensions outside 1..65535 (defect: Infinity / 0 dims)', () => {
  const capture = () => {
    const thumbs: ThumbnailData[] = [];
    const warnings: string[] = [];
    const sink = {
      addThumbnail: (t: ThumbnailData) => thumbs.push(t),
      warn: (code: string, message: string) => warnings.push(`${code}: ${message}`)
    } as unknown as AnnotationSink;
    return { thumbs, warnings, sink };
  };
  const feed = (begin: string) => {
    const c = capture();
    const t = new ThumbnailCollector(8);
    t.feed(` thumbnail begin ${begin} 8`, c.sink);
    t.feed(' AAECAwQFBgc=', c.sink);
    t.feed(' thumbnail end', c.sink);
    return c;
  };

  it('1x1 and 65535x65535 are kept', () => {
    expect(feed('1x1').thumbs.map((t) => [t.width, t.height])).toEqual([[1, 1]]);
    expect(feed('65535x65535').thumbs.map((t) => [t.width, t.height])).toEqual([[65535, 65535]]);
    expect(feed('1x1').warnings).toEqual([]);
  });

  for (const begin of ['0x1', '1x0', '65536x1', '1x65536', `${HUGE}x1`, `1x${HUGE}`]) {
    it(`${begin.length > 20 ? 'an overflowing size' : begin} is dropped with a warning`, () => {
      const c = feed(begin);
      expect(c.thumbs).toEqual([]);
      expect(c.warnings.length).toBe(1);
      expect(c.warnings[0].startsWith('dialect-metadata-invalid: thumbnail dimensions ')).toBe(true);
    });
  }

  it('the base64 body of a dropped thumbnail is not collected (the collector is idle)', () => {
    const c = capture();
    const t = new ThumbnailCollector(8);
    t.feed(' thumbnail begin 0x0 8', c.sink);
    expect(t.isActive).toBe(false);
  });

  it('a body over the 4/3 + 8 character bound is dropped; at the bound it is kept', () => {
    const c = capture();
    const at = new ThumbnailCollector(8); // bound: 8 * 4 / 3 + 8 = 18.67 characters
    at.feed(' thumbnail begin 1x1 8', c.sink);
    at.feed(` ${'A'.repeat(18)}`, c.sink);
    expect(at.isActive).toBe(true);
    const over = new ThumbnailCollector(8);
    over.feed(' thumbnail begin 1x1 8', c.sink);
    over.feed(` ${'A'.repeat(19)}`, c.sink);
    expect(over.isActive).toBe(false);
  });
});

/** A finished IR of `n` extruded unit segments along X. */
function makeIR(n: number): ToolpathIR {
  const b = new ToolpathIRBuilder({ parserVersion: 'test', units: 'mm', unitsSource: 'known' });
  for (let i = 0; i < n; i++) {
    b.addSegment({
      x0: i,
      y0: 0,
      z0: 0.2,
      x1: i + 1,
      y1: 0,
      z1: 0.2,
      e: 1,
      kind: MoveKind.Extrude,
      layer: 0,
      srcByte: i * 10
    });
  }
  return b.finalize();
}

function applied(fill: (s: BufferedAnnotationSink) => void, segments = 4) {
  const sink = new BufferedAnnotationSink('t');
  fill(sink);
  const ir = makeIR(segments);
  const md: DialectMetadata = { dialects: [] };
  sink.apply(ir, md, () => undefined);
  return { ir, md };
}

describe('BufferedAnnotationSink budgets (untrusted counts)', () => {
  const png = (i: number): ThumbnailData => ({ width: 1, height: 1, mime: 'image/png', bytes: new Uint8Array([i]) });

  it('keeps 8 thumbnails', () => {
    expect(applied((s) => [...Array(9).keys()].forEach((i) => s.addThumbnail(png(i)))).md.thumbnails?.length).toBe(8);
  });

  it('keeps 512 raw entries, keys cut to 128 and values to 4096 characters', () => {
    const { md } = applied((s) => {
      for (let i = 0; i < 513; i++) s.setRaw(`k${i}`, 'v');
    });
    expect(Object.keys(md.raw ?? {}).length).toBe(512);
    expect(md.raw?.k512).toBeUndefined();
    expect(applied((s) => s.setRaw('k', 'v'.repeat(5000))).md.raw?.k.length).toBe(4096);
    const long = applied((s) => s.setRaw('x'.repeat(200), 'v')).md.raw ?? {};
    expect(Object.keys(long).map((k) => k.length)).toEqual([128]);
  });

  it('keeps 100 distinct warnings', () => {
    const { ir } = applied((s) => {
      for (let i = 0; i < 101; i++) s.warn(`w${i}`, 'm');
    });
    expect(ir.header.warnings.filter((w) => w.code.startsWith('w')).length).toBe(100);
  });

  it('keeps 10,000 object names, each cut to 256 characters', () => {
    const { ir } = applied((s) => {
      for (let v = 1; v <= 10_001; v++) s.defineObject(v, v === 1 ? 'n'.repeat(300) : 'o');
    });
    expect(ir.objects.length).toBe(10000);
    expect(ir.objects[0].name?.length).toBe(256);
  });

  it('keeps 64 filaments and 64 tool entries', () => {
    const { md, ir } = applied((s) => {
      for (let i = 0; i < 65; i++) {
        s.setFilament({ slot: i });
        s.setToolInfo(i, { material: 'PLA' });
      }
    });
    expect(md.filaments?.length).toBe(64);
    expect(ir.tools.filter((t) => t.material === 'PLA').length).toBe(64);
  });

  it('Orca: 70 filament slots → 64 filaments and 64 tools (the sink caps them)', () => {
    const types = Array.from({ length: 70 }, () => 'PLA').join(';');
    const r = annotate([orcaBambu()], [ORCA, 'G1 X1 E1', `; filament_type = ${types}`]);
    expect(r.metadata?.filaments?.length).toBe(64);
    expect(r.ir.tools.filter((t) => t.material === 'PLA').length).toBe(64);
  });

  it('a tool colour must be exactly six hex digits', () => {
    const { ir } = applied((s) => {
      s.setToolInfo(0, { colorHex: '#FF0000' });
      s.setToolInfo(1, { colorHex: '#FF0000zz' });
    });
    expect(ir.tools.find((t) => t.id === 0)?.color).toEqual({ r: 1, g: 0, b: 0, a: 1 });
    expect(ir.tools.find((t) => t.id === 1)?.color).toBeUndefined();
  });

  it('range ops: 1,000,000 are kept silently; past that, ONE truncation warning', () => {
    const at = applied((s) => {
      for (let i = 0; i < 1_000_000; i++) s.setFeature(0, 0, 1);
    });
    expect(at.ir.header.warnings.filter((w) => w.code === 'dialect-annotation-truncated')).toEqual([]);
    const justOver = applied((s) => {
      for (let i = 0; i < 1_000_001; i++) s.setFeature(0, 0, 1);
    });
    expect(justOver.ir.header.warnings.filter((x) => x.code === 'dialect-annotation-truncated').length).toBe(1);
    const over = applied((s) => {
      for (let i = 0; i < 1_000_003; i++) s.setFeature(0, 0, 1);
    });
    const w = over.ir.header.warnings.filter((x) => x.code === 'dialect-annotation-truncated');
    expect(w.length).toBe(1);
    expect(w[0].count).toBe(1); // warned once, not once per dropped op
  });
});

describe('area points and Cura print time (survivors)', () => {
  it('parseAreaPoints accepts 64 points and rejects 65', () => {
    const pts = (n: number) => Array.from({ length: n }, (_, i) => `${i}x${i % 3}`).join(',');
    expect(parseAreaPoints(pts(64))?.length).toBe(64);
    expect(parseAreaPoints(pts(65))).toBeNull();
  });

  it('Cura: an overflowing `;TIME:` is not an estimate', () => {
    expect(annotate([cura()], [CURA, ';TIME:1e999', 'G1 X1 Y1']).metadata?.printEstimate).toBeUndefined();
    expect(annotate([cura()], [CURA, ';TIME:7', 'G1 X1 Y1']).metadata?.printEstimate?.seconds).toBe(7);
  });
});

describe('CNC detection scoring (survivors)', () => {
  const laser = (head: string) => grblLaser().detect({ headText: head, tailText: '' });
  const mill = (head: string) => grblMill().detect({ headText: head, tailText: '' });

  it('laser: a tool-on command needs S power', () => {
    expect(laser('M3\nG1 X10 Y10')).toBeNull();
    expect(laser('M3 S500\nG1 X10 Y10')?.evidence).toBe('M3 + S power, planar (no Z plunge)');
  });

  it('laser: M4 alone (dynamic power) is enough', () => {
    expect(laser('M4 S500\nG1 X10 Y10')?.evidence).toBe('M4 dynamic + S power, planar (no Z plunge)');
  });

  it('laser: a LinuxCNC header vetoes it', () => {
    expect(laser('(LinuxCNC)\nM3 S500\nG1 X10 Y10')).toBeNull();
  });

  it('mill: GRBL laser mode, a LightBurn header or a LinuxCNC header vetoes it', () => {
    const cut = 'M3 S1000\nG1 Z-1\nG1 X10';
    expect(mill(cut)?.evidence).toBe('M3 spindle + Z-plunge, no extrusion');
    expect(mill(`$32=1\n${cut}`)).toBeNull();
    expect(mill(`; LightBurn 1.4\n${cut}`)).toBeNull();
    expect(mill(`(LinuxCNC)\n${cut}`)).toBeNull();
  });

  it('mill: a Grbl banner is named in the evidence; M03 counts as M3', () => {
    expect(mill('; Grbl 1.1h\nM3 S1000\nG1 Z-1')?.evidence).toBe('Grbl banner + M3 + Z-plunge');
    expect(mill('M03 S1000\nG1 Z-1')?.evidence).toBe('M3 spindle + Z-plunge, no extrusion');
  });
});
