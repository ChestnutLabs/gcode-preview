/** A finished IR of `n` extruded unit segments along X, srcBytes 0, 10, 20, … */
function makeIR(n: number): ToolpathIR {
  const b = new ToolpathIRBuilder({ parserVersion: 'test', units: 'mm', unitsSource: 'known' });
  for (let i = 0; i < n; i++) {
    b.addSegment({ x0: i, y0: 0, z0: 0.2, x1: i + 1, y1: 0, z1: 0.2, e: 1, kind: MoveKind.Extrude, layer: 0, srcByte: i * 10 });
  }
  return b.finalize();
}

/** Parse + annotate exactly as the worker does. */
function annotate(adapters: DialectAdapter[], text: string) {
  const r = createDialectRunner(adapters).createRun({
    selection: 'auto',
    headText: text.slice(0, 65536),
    tailText: text.slice(-16384)
  });
  expect(r).not.toBeNull();
  const { ir } = parseGcodeToIR(text, { onComment: r!.onComment, onCommand: r!.onCommand });
  const { metadata } = r!.finalize(ir);
  return { ir, metadata };
}

function stub(
  id: string,
  kind: DialectAdapter['kind'],
  confidence: DialectDetection['confidence'],
  extra: Partial<DialectAdapter> = {}
): DialectAdapter {
  return { id, displayName: id, kind, detect: () => ({ dialectId: id, kind, confidence, evidence: id }), ...extra };
}

function applySink(sink: BufferedAnnotationSink, ir: ToolpathIR, md: DialectMetadata = { dialects: [] }) {
  const conflicts: string[] = [];
  sink.apply(ir, md, (code) => conflicts.push(code));
  return { md, conflicts };
}

describe('print-time estimates of a day or more (defect: dropped)', () => {
  it('parseHmsToSeconds reads the PrusaSlicer/Orca `Nd` day field', () => {
    expect(parseHmsToSeconds('1d 2h 3m 4s')).toBe(93784);
    expect(parseHmsToSeconds('2d 0h 0m 0s')).toBe(172800);
    expect(parseHmsToSeconds('1d')).toBe(86400);
    expect(parseHmsToSeconds('1h 2m 3s')).toBe(3723);
    expect(parseHmsToSeconds('0d 0h 0m 0s')).toBeNull();
  });

  it('PrusaSlicer keeps a 24 h+ `estimated printing time (normal mode)`', () => {
    const g = ['; generated by PrusaSlicer 2.8.1', 'G1 X1 Y1', '; estimated printing time (normal mode) = 1d 0h 7m 26s'];
    expect(annotate([prusaSlicer()], g.join('\n')).metadata?.printEstimate?.seconds).toBe(86846);
  });

  it('Orca keeps a 24 h+ `total estimated time`', () => {
    const g = ['; generated by OrcaSlicer 2.1.1', 'G1 X1 Y1', '; total estimated time: 1d 2h 0m 1s'];
    expect(annotate([orcaBambu()], g.join('\n')).metadata?.printEstimate?.seconds).toBe(93601);
  });
});

describe('Bambu Studio / OrcaSlicer one-line print-time header (defect: dropped)', () => {
  it('reads the total from `model printing time: …; total estimated time: …`', () => {
    const g = [
      '; HEADER_BLOCK_START',
      '; BambuStudio 01.09.00.70',
      '; model printing time: 1h 53m 22s; total estimated time: 2h 0m 34s',
      '; HEADER_BLOCK_END',
      'G1 X1 Y1'
    ];
    const est = annotate([orcaBambu()], g.join('\n')).metadata?.printEstimate;
    expect(est?.seconds).toBe(7234);
    expect(est?.source.evidence).toBe('; total estimated time: 2h 0m 34s');
  });

  it('falls back to the model time when the total part is unreadable', () => {
    const g = ['; BambuStudio 01.09.00.70', '; model printing time: 5m; total estimated time: garbage', 'G1 X1'];
    expect(annotate([orcaBambu()], g.join('\n')).metadata?.printEstimate?.seconds).toBe(300);
  });
});

describe('registry: detection and containment', () => {
  it('the higher-confidence adapter of a kind wins, whatever the registration order', () => {
    for (const order of [
      [stub('low', 'slicer', 'inferred'), stub('high', 'slicer', 'known')],
      [stub('high', 'slicer', 'known'), stub('low', 'slicer', 'inferred')]
    ]) {
      const run = createDialectRunner(order).createRun({ selection: 'auto', headText: '', tailText: '' });
      expect(run?.detections.map((d) => d.dialectId)).toEqual(['high']);
    }
  });

  it('an adapter whose detect() throws is skipped; the others still run', () => {
    const boom = stub('boom', 'slicer', 'known', {
      detect: () => {
        throw new Error('detect blew up');
      }
    });
    const run = createDialectRunner([boom, stub('fw', 'firmware', 'known')]).createRun({
      selection: 'auto',
      headText: '',
      tailText: ''
    });
    expect(run?.detections.map((d) => d.dialectId)).toEqual(['fw']);
  });

  it('an adapter that throws once is disabled for the rest of the run (one warning, no more calls)', () => {
    let calls = 0;
    const flaky = stub('flaky', 'slicer', 'known', {
      onComment() {
        calls++;
        throw new Error('bad comment');
      }
    });
    const run = createDialectRunner([flaky]).createRun({ selection: 'auto', headText: '', tailText: '' })!;
    run.onComment('a', 0);
    run.onComment('b', 10);
    run.onComment('c', 20);
    const ir = makeIR(3);
    run.finalize(ir);
    expect(calls).toBe(1);
    const w = ir.header.warnings.find((x) => x.code === 'adapter-failed');
    expect(w?.count).toBe(1);
    expect(w?.message).toBe("adapter 'flaky' failed: bad comment");
  });
});

describe('BufferedAnnotationSink guards', () => {
  it('drops a range with a negative start instead of writing from the buffer tail', () => {
    const ir = makeIR(5);
    const sink = new BufferedAnnotationSink('t');
    // A typed-array fill treats a negative start as counted from the end, so these would hit 3..4.
    sink.setFeature(-2, 4, 7);
    sink.setObject(-1, 4, 3);
    applySink(sink, ir);
    expect(Array.from(ir.segments.feature)).toEqual([0, 0, 0, 0, 0]);
    expect(Array.from(ir.segments.object)).toEqual([0, 0, 0, 0, 0]);
  });

  it('rejects a move-kind request that mixes an allowed bit with a motion bit', () => {
    const ir = makeIR(2);
    const sink = new BufferedAnnotationSink('t');
    sink.addMoveKind(0, 1, MoveKind.Wipe | MoveKind.Travel);
    applySink(sink, ir);
    expect(Array.from(ir.segments.kind)).toEqual([1, 1]); // Extrude only: nothing added
    expect(ir.header.warnings.map((w) => w.code)).toContain('dialect-kind-not-allowlisted');
  });

  it('keeps the FIRST print estimate and the FIRST filament-usage source', () => {
    const ir = makeIR(1);
    const sink = new BufferedAnnotationSink('t');
    const src = (evidence: string) => ({ adapterId: 't', evidence });
    sink.setPrintEstimate({ seconds: 100, mode: 'normal', source: src('first') });
    sink.setPrintEstimate({ seconds: 200, mode: 'silent', source: src('second') });
    sink.setFilamentUsage({ lengthMm: 10, source: src('len') });
    sink.setFilamentUsage({ weightG: 3, source: src('weight') });
    const { md } = applySink(sink, ir);
    expect(md.printEstimate?.seconds).toBe(100);
    expect(md.filamentUsage).toEqual({ lengthMm: 10, volumeCm3: undefined, weightG: 3, source: src('len') });
  });

  it('a later adapter does not replace an earlier adapter’s filament usage', () => {
    const ir = makeIR(1);
    const md: DialectMetadata = { dialects: [] };
    const a = new BufferedAnnotationSink('a');
    a.setFilamentUsage({ lengthMm: 10, source: { adapterId: 'a', evidence: 'a' } });
    const b = new BufferedAnnotationSink('b');
    b.setFilamentUsage({ lengthMm: 99, source: { adapterId: 'b', evidence: 'b' } });
    applySink(a, ir, md);
    applySink(b, ir, md);
    expect(md.filamentUsage?.lengthMm).toBe(10);
  });

  it('discloses a second machine geometry as a conflict', () => {
    const ir = makeIR(1);
    const md: DialectMetadata = { dialects: [] };
    const machine = (x: number) => ({
      bed: { kind: 'rect' as const, min: { x: 0, y: 0 }, max: { x, y: x } },
      origin: { x: 0, y: 0 },
      confidence: 'inferred' as const,
      source: { adapterId: 't', evidence: 'e' }
    });
    const a = new BufferedAnnotationSink('a');
    a.setMachine(machine(200));
    const b = new BufferedAnnotationSink('b');
    b.setMachine(machine(300));
    expect(applySink(a, ir, md).conflicts).toEqual([]);
    expect(applySink(b, ir, md).conflicts).toEqual(['dialect-conflict']);
    expect(md.machine?.bed).toEqual({ kind: 'rect', min: { x: 0, y: 0 }, max: { x: 300, y: 300 } });
  });

  it('objectBounds covers only extruded segments that belong to an object', () => {
    const ir = makeIR(4); // segments x: [0,1] [1,2] [2,3] [3,4]
    const sink = new BufferedAnnotationSink('t');
    sink.setObject(1, 2, 1);
    applySink(sink, ir);
    expect(ir.objectBounds.min.x).toBe(1);
    expect(ir.objectBounds.max.x).toBe(3);
  });

  it('ignores an object definition for channel value 0 (0 = no object)', () => {
    const ir = makeIR(2);
    const sink = new BufferedAnnotationSink('t');
    sink.setObject(0, 1, 1);
    sink.defineObject(0, 'none');
    sink.defineObject(1, 'cube');
    applySink(sink, ir);
    expect(Object.keys(ir.objects)).toEqual(['0']);
    expect(ir.objects[0]).toEqual({ id: '1', name: 'cube' });
  });
});

describe('annotation range helpers', () => {
  it('segAtOrAfterByte: a marker at a command’s own byte selects that command’s segment', () => {
    const ir = makeIR(4); // srcBytes 0, 10, 20, 30
    expect(segAtOrAfterByte(ir, 10)).toBe(1);
    expect(segAtOrAfterByte(ir, 11)).toBe(2);
    expect(segAtOrAfterByte(ir, 31)).toBe(4);
  });

  it('end-only object markers apply nothing and claim no objects', () => {
    const ir = makeIR(3);
    const t = new PrintingObjectTracker();
    expect(t.handle('stop printing object a id:1', 5)).toBe(true);
    const sink = new BufferedAnnotationSink('t');
    expect(t.apply(ir, sink)).toBe(0);
    applySink(sink, ir);
    expect(ir.header.capabilities.objects).not.toBe('known');
  });

  it('a second START inside an open bracket folds into it (the bracket starts at the first)', () => {
    const ir = makeIR(5); // srcBytes 0..40
    const sink = new BufferedAnnotationSink('t');
    const n = applyWipeRanges(
      ir,
      [
        { srcByte: 0, open: true },
        { srcByte: 20, open: true },
        { srcByte: 30, open: false }
      ],
      sink
    );
    applySink(sink, ir);
    expect(n).toBe(1);
    const w = 1 | MoveKind.Wipe;
    expect(Array.from(ir.segments.kind)).toEqual([w, w, w, 1, 1]);
  });

  it('a START left open at end of file closes at the last segment', () => {
    const ir = makeIR(4);
    const sink = new BufferedAnnotationSink('t');
    expect(applyWipeRanges(ir, [{ srcByte: 20, open: true }], sink)).toBe(1);
    applySink(sink, ir);
    expect(Array.from(ir.segments.kind)).toEqual([1, 1, 1 | MoveKind.Wipe, 1 | MoveKind.Wipe]);
  });

  it('applySegmentMarkers ignores a marker that starts past the segment count', () => {
    const writes: number[][] = [];
    const n = applySegmentMarkers(
      [
        { segIndex: 5, value: 1 },
        { segIndex: 9, value: 0 }
      ],
      3,
      (a, b, v) => writes.push([a, b, v])
    );
    expect(n).toBe(0);
    expect(writes).toEqual([]);
  });

  it('a four-point bed whose corners do not share Y values is a polygon, not a rect', () => {
    const pts = parseAreaPoints('0x0,10x0,10x5,0x10')!;
    expect(bedFromPoints(pts, 't', 'e', undefined, undefined, undefined).bed.kind).toBe('polygon');
    expect(bedFromPoints(parseAreaPoints('0x0,10x0,10x10,0x10')!, 't', 'e', undefined, undefined, undefined).bed.kind).toBe(
      'rect'
    );
  });
});

describe('ThumbnailCollector bounds', () => {
  const capture = () => {
    const thumbs: ThumbnailData[] = [];
    const sink = { addThumbnail: (t: ThumbnailData) => thumbs.push(t) } as unknown as AnnotationSink;
    return { thumbs, sink };
  };

  it('accepts a thumbnail whose declared size equals the cap', () => {
    const { thumbs, sink } = capture();
    const c = new ThumbnailCollector(8);
    c.feed(' thumbnail begin 1x1 8', sink);
    c.feed(' AAECAwQFBgc=', sink); // 8 bytes: 00..07
    c.feed(' thumbnail end', sink);
    expect(thumbs.length).toBe(1);
    expect(Array.from(thumbs[0].bytes)).toEqual([0, 1, 2, 3, 4, 5, 6, 7]);
  });

  it('drops a thumbnail whose data outgrows its declared size (lying header)', () => {
    const { thumbs, sink } = capture();
    const c = new ThumbnailCollector(8);
    c.feed(' thumbnail begin 1x1 8', sink);
    c.feed(' AAECAwQFBgcICQoLDA0ODxAREhMU', sink); // 28 chars > 8 * 4/3 + 8
    expect(c.isActive).toBe(false);
    c.feed(' thumbnail end', sink);
    expect(thumbs.length).toBe(0);
  });
});

describe('slicer adapters', () => {
  it('a re-opened object id reuses its channel value (one object, not two)', () => {
    const g = [
      '; generated by PrusaSlicer 2.9.1',
      'M83',
      '; printing object a.stl id:1 copy 0',
      'G1 X10 Y10 E1',
      '; stop printing object a.stl id:1 copy 0',
      '; printing object b.stl id:2 copy 0',
      'G1 X20 Y10 E1',
      '; stop printing object b.stl id:2 copy 0',
      '; printing object a.stl id:1 copy 0',
      'G1 X30 Y10 E1',
      '; stop printing object a.stl id:1 copy 0'
    ];
    const { ir } = annotate([prusaSlicer()], g.join('\n'));
    expect(Array.from(ir.segments.object)).toEqual([1, 2, 1]);
    expect(ir.objects.map((o) => o.name)).toEqual(['a.stl', 'b.stl']);
  });

  it('Orca: a file with only FLUSH brackets still reports feature roles as known', () => {
    const g = ['; generated by OrcaSlicer 2.1.1', 'M83', 'G1 X1 Y1 E1', '; FLUSH_START', 'G1 X2 Y1 E1', '; FLUSH_END', 'G1 X3 Y1 E1'];
    expect(annotate([orcaBambu()], g.join('\n')).ir.header.capabilities.featureRoles).toBe('known');
  });

  it('Orca: every filament slot is kept when the colour list is shorter than the type list', () => {
    const g = ['; generated by OrcaSlicer 2.1.1', 'G1 X1 Y1', '; filament_type = PLA;PETG;ABS', '; filament_colour = #FF0000'];
    const { metadata } = annotate([orcaBambu()], g.join('\n'));
    expect(metadata?.filaments?.map((f) => f.type)).toEqual(['PLA', 'PETG', 'ABS']);
    expect(metadata?.filaments?.map((f) => f.color)).toEqual(['#FF0000', undefined, undefined]);
  });

  it('Cura: `;TIME:0` is not a print estimate', () => {
    const g = [';Generated with Cura_SteamEngine 5.6.0', ';TIME:0', 'G1 X1 Y1'];
    expect(annotate([cura()], g.join('\n')).metadata?.printEstimate).toBeUndefined();
  });
});

describe('CNC dialect detection and honesty tier', () => {
  it('an experimental tier downgrades only the claims the file made (no fabricated claims)', () => {
    const g = ['Grbl 1.1h', 'M3 S12000', 'G0 X0 Y0 Z5', 'G1 Z-1 F100', 'G1 X10'];
    const { ir } = annotate([grblMill()], g.join('\n'));
    expect(ir.header.capabilities.cutMoves).toBe('inferred');
    expect(ir.header.capabilities.cannedCycles).toBe('unavailable');
  });

  it('M82/M83 marks a file as FDM, so a spindle-looking file is not a laser', () => {
    expect(grblLaser().detect({ headText: 'M83\nM3 S1000\nG1 X10 Y10', tailText: '' })).toBeNull();
    expect(grblLaser().detect({ headText: 'M3 S1000\nG1 X10 Y10', tailText: '' })?.confidence).toBe('inferred');
  });

  it('a `%` program envelope alone (no spindle) is not LinuxCNC evidence', () => {
    expect(linuxCnc().detect({ headText: '%\nG1 X1 Z-1\n%', tailText: '' })).toBeNull();
    expect(linuxCnc().detect({ headText: '%\nM3 S1000\nG1 X1 Z-1\n%', tailText: '' })?.confidence).toBe('inferred');
  });
});

describe('ideaMaker object names', () => {
  it('a `;PRINTING:` name is used by the next `;PRINTING_ID:` only, not by later ids', () => {
    const g = [
      ';Sliced by ideaMaker 4.4.0',
      'M83',
      ';PRINTING: cube',
      ';PRINTING_ID: 0',
      'G1 X10 Y10 E1',
      ';PRINTING_ID: 1',
      'G1 X20 Y10 E1'
    ];
    const { ir } = annotate([ideaMaker()], g.join('\n'));
    expect(Array.from(ir.segments.object)).toEqual([1, 2]);
    expect(ir.objects).toEqual([{ id: '1', name: 'cube' }]); // id 1 (value 2) had no name line
  });
});
